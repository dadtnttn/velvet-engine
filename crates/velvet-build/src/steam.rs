//! Optional Steamworks surface for host export config.
//!
//! Init / achievement / presence hooks call without panicking when the Steam
//! client is absent (loopback no-op backend). Feature `steam` can later wire a
//! real SDK; default builds use this safe stub.

use serde::{Deserialize, Serialize};

/// Steam integration status.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SteamStatus {
    /// Whether a Steam client appears available.
    pub client_available: bool,
    /// App id from config (0 = unset).
    pub app_id: u32,
    /// Backend: `none` | `stub` | `steamworks` (feature).
    pub backend: String,
    /// Last error or note.
    pub note: String,
}

/// Host export / runtime Steam config.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SteamConfig {
    /// Steam App ID.
    pub app_id: u32,
    /// Enable Steam integration when client present.
    pub enabled: bool,
}

impl Default for SteamConfig {
    fn default() -> Self {
        Self {
            app_id: 0,
            enabled: true,
        }
    }
}

/// In-memory Steam hook (no panic without client).
#[derive(Debug, Clone)]
pub struct SteamHook {
    /// Status after init.
    pub status: SteamStatus,
    /// Unlocked achievements (local mirror).
    unlocked: Vec<String>,
    /// Rich presence key/values.
    presence: Vec<(String, String)>,
}

impl SteamHook {
    /// Initialize Steam for the given config. Never panics if Steam is missing.
    pub fn init(config: &SteamConfig) -> Self {
        if !config.enabled {
            return Self {
                status: SteamStatus {
                    client_available: false,
                    app_id: config.app_id,
                    backend: "none".into(),
                    note: "steam disabled in config".into(),
                },
                unlocked: Vec::new(),
                presence: Vec::new(),
            };
        }
        let client_available = detect_steam_client();
        let (backend, note) = if client_available {
            (
                "stub".to_string(),
                "steam client detected; using stub hooks (no steamworks feature)".into(),
            )
        } else {
            (
                "stub".to_string(),
                "steam client absent; achievement/presence are local no-ops".into(),
            )
        };
        Self {
            status: SteamStatus {
                client_available,
                app_id: config.app_id,
                backend,
                note,
            },
            unlocked: Vec::new(),
            presence: Vec::new(),
        }
    }

    /// Unlock an achievement id. Returns whether recorded (always true on stub).
    pub fn set_achievement(&mut self, id: &str) -> bool {
        if id.is_empty() {
            return false;
        }
        if !self.unlocked.iter().any(|a| a == id) {
            self.unlocked.push(id.to_string());
        }
        true
    }

    /// Whether achievement was unlocked this session.
    pub fn is_achievement_unlocked(&self, id: &str) -> bool {
        self.unlocked.iter().any(|a| a == id)
    }

    /// Set rich presence key.
    pub fn set_presence(&mut self, key: &str, value: &str) -> bool {
        if key.is_empty() {
            return false;
        }
        if let Some(slot) = self.presence.iter_mut().find(|(k, _)| k == key) {
            slot.1 = value.into();
        } else {
            self.presence.push((key.into(), value.into()));
        }
        true
    }

    /// Read presence.
    pub fn presence(&self) -> &[(String, String)] {
        &self.presence
    }

    /// Unlocked list.
    pub fn unlocked(&self) -> &[String] {
        &self.unlocked
    }

    /// Mirror earned achievement ids from a session
    /// (`AchievementState::earned_set`). Returns newly recorded ids.
    /// This is the single wiring point a real Steamworks client uses:
    /// with the SDK linked, each new id also fires the native unlock call.
    pub fn sync_earned(&mut self, earned: impl IntoIterator<Item = String>) -> Vec<String> {
        let mut newly = Vec::new();
        for id in earned {
            if id.is_empty() {
                continue;
            }
            if !self.unlocked.iter().any(|a| a == &id) {
                self.unlocked.push(id.clone());
                newly.push(id);
            }
        }
        newly
    }
}

/// One Workshop item for manual upload (`steamcmd` script generated by
/// [`write_workshop_upload_script`]; uploading itself needs the SDK + login).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct WorkshopItem {
    /// Workshop title.
    pub title: String,
    /// Description (supports Steam BBCode).
    #[serde(default)]
    pub description: String,
    /// Content directory to upload.
    pub content_dir: String,
    /// Preview image path.
    #[serde(default)]
    pub preview: String,
    /// Tags.
    #[serde(default)]
    pub tags: Vec<String>,
    /// Visibility: `public` | `friends` | `private`.
    #[serde(default = "default_workshop_visibility")]
    pub visibility: String,
}

fn default_workshop_visibility() -> String {
    "public".into()
}

impl WorkshopItem {
    /// Validate (non-empty title + existing content dir + preview).
    pub fn validate(&self) -> Result<(), String> {
        if self.title.trim().is_empty() {
            return Err("workshop title is empty".into());
        }
        if !std::path::Path::new(&self.content_dir).is_dir() {
            return Err(format!(
                "workshop content dir missing: {}",
                self.content_dir
            ));
        }
        if !self.preview.trim().is_empty() && !std::path::Path::new(&self.preview).is_file() {
            return Err(format!("workshop preview missing: {}", self.preview));
        }
        if !["public", "friends", "private"].contains(&self.visibility.as_str()) {
            return Err(format!("bad workshop visibility: {}", self.visibility));
        }
        Ok(())
    }
}

/// Write `workshop.json` manifest + `upload_workshop.txt` steamcmd script.
///
/// Run the script with:
/// `steamcmd +login <user> +workshop_build_item <script> +quit`
/// (needs the Steam SDK + partner login; generation itself is offline).
pub fn write_workshop_upload_script(
    out_dir: &std::path::Path,
    app_id: u32,
    item: &WorkshopItem,
) -> std::io::Result<std::path::PathBuf> {
    item.validate()
        .map_err(|e| std::io::Error::new(std::io::ErrorKind::InvalidInput, e))?;
    std::fs::create_dir_all(out_dir)?;
    std::fs::write(
        out_dir.join("workshop.json"),
        serde_json::to_string_pretty(item).unwrap(),
    )?;
    // Escape backslashes for steamcmd's config parser.
    let esc = |s: &str| s.replace('\\', "\\\\");
    let script = format!(
        "\"AppID\" \"{app_id}\"\n\"WorkshopItem\" {{\n  \"Title\" \"{title}\"\n  \"Description\" \"{desc}\"\n  \"Content\" \"{content}\"\n  \"Preview\" \"{preview}\"\n  \"Visibility\" \"{vis}\"\n  \"Tags\" {{ {tags} }}\n}}\n",
        title = esc(&item.title),
        desc = esc(&item.description).replace('"', "'"),
        content = esc(&item.content_dir),
        preview = esc(&item.preview),
        vis = item.visibility,
        tags = item
            .tags
            .iter()
            .enumerate()
            .map(|(i, t)| format!("\"{i}\" \"{}\"", esc(t).replace('"', "'")))
            .collect::<Vec<_>>()
            .join(" "),
    );
    let path = out_dir.join("upload_workshop.txt");
    std::fs::write(&path, script)?;
    Ok(path)
}

fn detect_steam_client() -> bool {
    // Non-invasive: check common Steam install env / path without loading DLL.
    if std::env::var_os("SteamAppId").is_some() || std::env::var_os("SteamOverlayGameId").is_some()
    {
        return true;
    }
    let candidates = [
        r"C:\Program Files (x86)\Steam\steam.exe",
        r"C:\Program Files\Steam\steam.exe",
        "/usr/bin/steam",
        "/usr/games/steam",
    ];
    candidates.iter().any(|p| std::path::Path::new(p).is_file())
}

/// Write a steam_appid.txt next to an export binary (Steam requirement).
pub fn write_steam_appid_file(out_dir: &std::path::Path, app_id: u32) -> std::io::Result<()> {
    std::fs::write(out_dir.join("steam_appid.txt"), format!("{app_id}\n"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn init_without_client_does_not_panic_and_achievements_work() {
        let mut hook = SteamHook::init(&SteamConfig {
            app_id: 480,
            enabled: true,
        });
        assert_eq!(hook.status.app_id, 480);
        assert!(hook.status.backend == "stub" || hook.status.backend == "none");
        assert!(hook.set_achievement("FIRST_ENDING"));
        assert!(hook.is_achievement_unlocked("FIRST_ENDING"));
        assert!(hook.set_presence("story", "chapter_1"));
        assert!(hook
            .presence()
            .iter()
            .any(|(k, v)| k == "story" && v == "chapter_1"));
        assert!(!hook.set_achievement(""));
    }

    #[test]
    fn disabled_config() {
        let hook = SteamHook::init(&SteamConfig {
            app_id: 0,
            enabled: false,
        });
        assert_eq!(hook.status.backend, "none");
    }

    #[test]
    fn sync_earned_dedups_and_reports_new() {
        let mut hook = SteamHook::init(&SteamConfig {
            app_id: 480,
            enabled: true,
        });
        let newly = hook.sync_earned(vec!["A".into(), "B".into(), String::new()]);
        assert_eq!(newly, vec!["A".to_string(), "B".to_string()]);
        assert!(hook.sync_earned(vec!["A".into()]).is_empty());
        assert!(hook.is_achievement_unlocked("B"));
    }

    #[test]
    fn workshop_script_generation() {
        let dir = tempfile::tempdir().unwrap();
        let content = dir.path().join("mod");
        std::fs::create_dir_all(&content).unwrap();
        let preview = dir.path().join("p.png");
        std::fs::write(&preview, b"png").unwrap();
        let item = WorkshopItem {
            title: "My Mod".into(),
            description: "Say \"hi\"".into(),
            content_dir: content.display().to_string(),
            preview: preview.display().to_string(),
            tags: vec!["VN".into()],
            visibility: "public".into(),
        };
        let out = dir.path().join("ws");
        let script = write_workshop_upload_script(&out, 480, &item).unwrap();
        assert!(out.join("workshop.json").is_file());
        let text = std::fs::read_to_string(script).unwrap();
        assert!(text.contains("\"AppID\" \"480\""));
        assert!(text.contains("My Mod"));
        // invalid items fail before touching disk semantics
        let mut bad = item.clone();
        bad.title.clear();
        assert!(write_workshop_upload_script(&out, 480, &bad).is_err());
        bad = item.clone();
        bad.visibility = "galaxy".into();
        assert!(write_workshop_upload_script(&out, 480, &bad).is_err());
    }
}
