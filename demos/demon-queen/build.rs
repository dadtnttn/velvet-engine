use std::fs;
use std::path::{Path, PathBuf};

const ICON: &str = "data/assets/title/app_icon.ico";
const STORY: &str = "story/prologue.json";
const STYLES: &str = "data/styles/main_menu.vcss";
const LOCALES: &str = "data/locales";
const ASSETS: &str = "data/assets";
const MENU_OVERLAY: &str = "title/demon_queen_menu_overlay_native_705x1050.png";

fn main() {
    if std::env::var_os("CARGO_FEATURE_PORTABLE").is_some() {
        generate_portable_bundle();
    }
    embed_windows_metadata();
}

fn generate_portable_bundle() {
    println!("cargo:rerun-if-changed={STORY}");
    println!("cargo:rerun-if-changed={STYLES}");
    println!("cargo:rerun-if-changed={LOCALES}");
    println!("cargo:rerun-if-changed={ASSETS}/native_1080p");
    println!("cargo:rerun-if-changed={ASSETS}/{MENU_OVERLAY}");
    // The release's packed art (tools/build_release.py): the same pictures under the same
    // names, AVIF inside; embedded instead of the originals where there.
    println!("cargo:rerun-if-env-changed=DEMON_QUEEN_PACKED_ART");
    let packed = std::env::var_os("DEMON_QUEEN_PACKED_ART").map(PathBuf::from);
    if let Some(packed) = &packed {
        println!("cargo:rerun-if-changed={}", packed.display());
    }

    let manifest = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is available"),
    );
    let assets_root = manifest.join(ASSETS);

    assert!(
        assets_root.join("native_1080p").is_dir(),
        "portable builds require the private media pack in data/assets/native_1080p; see README.md"
    );

    let mut asset_paths = Vec::new();
    collect_png_paths(
        &assets_root,
        &assets_root.join("native_1080p"),
        &mut asset_paths,
    );
    let menu_overlay = assets_root.join(MENU_OVERLAY);
    assert!(
        menu_overlay.is_file(),
        "portable menu overlay missing: {}",
        menu_overlay.display()
    );
    asset_paths.push(MENU_OVERLAY.to_string());
    asset_paths.sort();
    asset_paths.dedup();

    let mut locale_paths = fs::read_dir(manifest.join(LOCALES))
        .expect("locale directory exists")
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("json"))
        .collect::<Vec<_>>();
    locale_paths.sort();

    let mut generated = String::from(
        "// @generated by demos/demon-queen/build.rs; do not edit.\n\
         pub const STORY_JSON: &[u8] = include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/story/prologue.json\"));\n\
         pub const MAIN_MENU_VCSS: &str = include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/data/styles/main_menu.vcss\"));\n\
         pub const ASSET_COUNT: usize = ",
    );
    generated.push_str(&asset_paths.len().to_string());
    generated.push_str(
        ";\n\npub fn locale_bytes(code: &str) -> Option<&'static [u8]> {\n    match code {\n",
    );
    for path in &locale_paths {
        let code = path
            .file_stem()
            .and_then(|stem| stem.to_str())
            .expect("locale name is UTF-8");
        let include_path = format!("/data/locales/{code}.json");
        generated.push_str(&format!(
            "        {code:?} => Some(include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {include_path:?}))),\n"
        ));
    }
    generated.push_str(
        "        _ => None,\n    }\n}\n\npub fn asset_bytes(path: &str) -> Option<&'static [u8]> {\n    match path {\n",
    );
    for path in &asset_paths {
        let packed_file = packed
            .as_ref()
            .map(|dir| dir.join(path))
            .filter(|file| file.is_file());
        if let Some(file) = packed_file {
            let file = file.to_string_lossy().replace('\\', "/");
            generated.push_str(&format!(
                "        {path:?} => Some(include_bytes!({file:?})),\n"
            ));
            continue;
        }
        let include_path = format!("/data/assets/{path}");
        generated.push_str(&format!(
            "        {path:?} => Some(include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {include_path:?}))),\n"
        ));
    }
    generated.push_str("        _ => None,\n    }\n}\n");

    let output = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR is available"))
        .join("demon_queen_portable.rs");
    fs::write(&output, generated).expect("portable source catalog can be written");
}

/// Folders kept beside the art for review, which the game never asks for: not embedded.
const NOT_EMBEDDED: &[&str] = &["pre_4k_1080_approved", "review_only"];

/// Pictures no code, guion or story names, so the game never asks for them: not embedded.
const UNUSED_PICTURES: &[&str] = &[
    "native_1080p/cg/approved_cg11_memory_question_legacy.png",
    "native_1080p/cg/approved_cg12_seal_abdomen.png",
    "native_1080p/cg/approved_cg13_diagnosis_maids.png",
    "native_1080p/cg/approved_cg14_hidden_relief.png",
    "native_1080p/cg/approved_cg15_request_privacy.png",
    "native_1080p/cg/approved_cg18_explore_reflection_legacy.png",
    "native_1080p/cg/approved_promoted_p04_examination.png",
    "native_1080p/cg/approved_promoted_p04_nyxara_enters.png",
    "native_1080p/cg/hipno_etapa1_final.png",
    "native_1080p/cg/p01_avoid_reply.png",
    "native_1080p/cg/p01_button.png",
    "native_1080p/cg/p01_two_dorayaki.png",
    "native_1080p/cg/p01_two_messages.png",
];

fn collect_png_paths(root: &Path, directory: &Path, output: &mut Vec<String>) {
    let mut entries = fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("cannot read {}: {error}", directory.display()))
        .filter_map(Result::ok)
        .collect::<Vec<_>>();
    entries.sort_by_key(|entry| entry.path());
    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            let name = path
                .file_name()
                .and_then(|name| name.to_str())
                .unwrap_or_default();
            if !NOT_EMBEDDED.contains(&name) {
                collect_png_paths(root, &path, output);
            }
        } else if path.extension().and_then(|ext| ext.to_str()) == Some("png") {
            let relative = path
                .strip_prefix(root)
                .expect("asset stays below data/assets")
                .to_string_lossy()
                .replace('\\', "/");
            if !UNUSED_PICTURES.contains(&relative.as_str()) {
                output.push(relative);
            }
        }
    }
}

fn embed_windows_metadata() {
    println!("cargo:rerun-if-changed={ICON}");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }

    let mut resource = winresource::WindowsResource::new();
    resource
        .set_icon(ICON)
        .set("ProductName", "Demon Queen")
        .set(
            "FileDescription",
            "Demon Queen — Prologue · A game by Velvet Weaver",
        )
        .set("CompanyName", "Velvet Weaver")
        .set("InternalName", "Demon Queen")
        .set("OriginalFilename", "DemonQueen-Prologue-Portable.exe")
        .set("LegalCopyright", "Copyright © 2026 Velvet Weaver")
        .set("Comments", "Woven with Velvet Engine.");
    resource
        .compile()
        .expect("no se pudo incrustar el icono y metadatos de Demon Queen");
}
